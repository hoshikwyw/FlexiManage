/**
 * Handy aliases over the generated Supabase types (`npm run db:types`).
 * Import rows from here instead of digging into `Database['public']...`.
 */
import {
  Constants,
  type Database,
  type Enums,
  type Json,
  type Tables,
  type TablesInsert,
  type TablesUpdate,
} from './supabase'

export type { Database }

export type Profile = Tables<'profiles'>
export type ProfileUpdate = TablesUpdate<'profiles'>

export type Workspace = Tables<'workspaces'>
export type WorkspaceInsert = TablesInsert<'workspaces'>
export type WorkspaceUpdate = TablesUpdate<'workspaces'>

export type WorkspaceMember = Tables<'workspace_members'>
export type WorkspaceMemberInsert = TablesInsert<'workspace_members'>

export type Invitation = Tables<'invitations'>
export type InvitationInsert = TablesInsert<'invitations'>

export type AuditEvent = Tables<'audit_events'>

export type WorkspaceRole = Enums<'workspace_role'>
export const WORKSPACE_ROLES = Constants.public.Enums.workspace_role

// Content model (migration 004). `Record` is a TypeScript built-in, hence RecordRow.
export type Module = Tables<'modules'>
export type ModuleInsert = TablesInsert<'modules'>
export type ModuleUpdate = TablesUpdate<'modules'>

export type FieldDefinition = Tables<'field_definitions'>
export type FieldDefinitionInsert = TablesInsert<'field_definitions'>
export type FieldDefinitionUpdate = TablesUpdate<'field_definitions'>

export type FieldType = Enums<'field_type'>
export const FIELD_TYPES = Constants.public.Enums.field_type

export type RecordRow = Tables<'records'>
export type RecordInsert = TablesInsert<'records'>
export type RecordUpdate = TablesUpdate<'records'>

/** Shape of one entry of `field_definitions.options` (select fields only). */
export interface SelectOption {
  value: string
  label: string
}

/** Known keys of `field_definitions.settings`; unknown keys are preserved by the database. */
export interface FieldSettings {
  /** currency fields: ISO 4217 code, `^[A-Z]{3}$` */
  currency?: string
  /** number and currency fields: integer 0..6 */
  precision?: number
}

/**
 * Full row returned by `workspace_usage(p_workspace_id)` since migration 005:
 * modules, records, members, attachments, storage_bytes (`storage_bytes` is a JSON number).
 */
export type WorkspaceUsageRow =
  Database['public']['Functions']['workspace_usage']['Returns'][number]

/**
 * `p_patch` of `update_record(p_record_id, p_expected_updated_at, p_patch)` (contract C3,
 * migration 006). Every key is optional: `status: null` clears the status, `set` merges custom
 * values, `unset` removes keys (applied before `set`).
 */
export interface UpdateRecordPatch {
  title?: string
  status?: string | null
  set?: { [key: string]: Json }
  unset?: string[]
}

/** Row returned by `update_record` (the full `records` row). */
export type UpdateRecordResult = Database['public']['Functions']['update_record']['Returns']

// Attachments (migration 005). `storage_path` is generated by the database; clients insert
// only workspace_id, record_id, file_name, content_type and size_bytes. `uploaded_at`
// (migration 006) is null while the upload is pending.
export type Attachment = Tables<'attachments'>
export type AttachmentInsert = Pick<
  TablesInsert<'attachments'>,
  'workspace_id' | 'record_id' | 'file_name' | 'content_type' | 'size_bytes'
>

// Plans and limits (migration 007). Both tables are read-only for clients.
export type Plan = Tables<'plans'>
export type Subscription = Tables<'subscriptions'>
export type SubscriptionStatus = Enums<'subscription_status'>
export const SUBSCRIPTION_STATUSES = Constants.public.Enums.subscription_status

/**
 * One row of `workspace_entitlements(p_workspace_id)`: resource (members, modules, records,
 * storage_bytes, workspaces), plan, limit_value, current_value, over_limit. The `workspaces` row
 * is about the caller (workspaces they own vs. may own).
 */
export type WorkspaceEntitlementRow =
  Database['public']['Functions']['workspace_entitlements']['Returns'][number]

/** Resources a plan limits; the `resource` of contract C6 errors and entitlement rows. */
export type PlanResource = 'members' | 'modules' | 'records' | 'storage_bytes' | 'workspaces'

/**
 * DETAIL of a PT402 `plan_limit_exceeded` error (contract C6), JSON-encoded in
 * `PostgrestError.details` for direct table writes, and the `details` of the Edge Function
 * envelope `{ error: { code: 'plan_limit_exceeded', message, details } }`.
 */
export interface PlanLimitDetails {
  resource: PlanResource
  limit: number
  current: number
  plan: string
}
