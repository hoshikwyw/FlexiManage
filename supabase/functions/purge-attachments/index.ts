/**
 * POST /functions/v1/purge-attachments            (operators only: service-role key)
 *
 * Body:     {} or { limit?: 1..1000 }   (default 200 queue entries per call)
 * Success:  200 { data: { purged, alreadyGone, retryable, dead } }
 *             purged       objects removed from Storage by this call
 *             alreadyGone  queue entries processed whose object did not exist (any more)
 *             retryable    entries left in the queue with attempts < 10 (not reached yet, or failed
 *                          in this call): call again while retryable > 0
 *             dead         entries with attempts >= 10, no longer retried (operator action)
 * Errors:   401 unauthorized (no bearer), 403 forbidden (bearer is not the service-role
 *           key, e.g. a user JWT), 400 validation_error, 500 internal (the queue cannot be read).
 *
 * Drains `public.storage_deletion_queue` (migrations 005 and 006). Every deleted `attachments`
 * row (direct, cascade, sweep or reconciliation rejection) and every object without a row
 * enqueues its object; Postgres cannot call the Storage API and storage.objects refuses direct
 * SQL deletes, so this function removes the objects through the Storage API:
 *
 *   1. read the oldest `limit` queue entries with attempts < 10;
 *   2. per bucket, `storage.from(bucket).remove(names)` in chunks of 100 names (a request body,
 *      so long names cannot overflow a URL); Storage returns the objects it deleted, everything
 *      else in the chunk was already gone;
 *   3. delete the queue rows of successful chunks; for a failed chunk increment `attempts` and
 *      keep `last_error` (no throw: other chunks still complete).
 *
 * There is no "live row" check: storage_path embeds the attachment's primary key, ids are
 * generated by the database (clients have no insert grant on `id`), and a deleted id is never
 * issued again, so a queued name can never belong to a live row.
 *
 * Schedule: pg_cron job `purge-attachments` every 10 minutes through pg_net with the key from
 * Vault (migration 006, docs/operations.md, "Scheduled maintenance"). Removing a missing object
 * is not an error, so the call is idempotent and safe to run concurrently or repeatedly.
 * Not audited: it removes bytes whose deletion was already audited.
 */
import { z } from 'zod'
import { adminClient, requireServiceRole } from '../_shared/auth.ts'
import { AppError, jsonOk } from '../_shared/errors.ts'
import { createHandler } from '../_shared/handler.ts'

const bodySchema = z.object({ limit: z.number().int().min(1).max(1000).optional() }).strict()

const MAX_ATTEMPTS = 10
/** Names per Storage remove call. */
const REMOVE_CHUNK = 100
/** Ids per PostgREST `in` filter (short numeric ids). */
const ID_CHUNK = 200

interface QueueRow {
  id: number
  bucket_id: string
  object_name: string
  attempts: number
}

function chunks<T>(items: readonly T[], size: number): T[][] {
  const out: T[][] = []
  for (let i = 0; i < items.length; i += size) out.push(items.slice(i, i + size))
  return out
}

async function readBody(req: Request): Promise<z.output<typeof bodySchema>> {
  const text = await req.text()
  if (text.trim() === '') return {}
  let raw: unknown
  try {
    raw = JSON.parse(text)
  } catch {
    throw new AppError(400, 'validation_error', 'Request body must be valid JSON')
  }
  const result = bodySchema.safeParse(raw)
  if (!result.success) {
    throw new AppError(
      400,
      'validation_error',
      'Invalid request body',
      z.flattenError(result.error),
    )
  }
  return result.data
}

Deno.serve(
  createHandler(['POST'], async (req, { cors }) => {
    requireServiceRole(req)
    const body = await readBody(req)
    const limit = body.limit ?? 200
    const admin = adminClient()

    const { data: queue, error: queueError } = await admin
      .from('storage_deletion_queue')
      .select('id, bucket_id, object_name, attempts')
      .lt('attempts', MAX_ATTEMPTS)
      .order('enqueued_at', { ascending: true })
      .order('id', { ascending: true })
      .limit(limit)
    if (queueError) throw new AppError(500, 'internal', 'Could not read the deletion queue')

    const rows = (queue ?? []) as QueueRow[]
    let purged = 0
    let alreadyGone = 0
    const done: number[] = []
    const failed: { row: QueueRow; message: string }[] = []

    const byBucket = new Map<string, QueueRow[]>()
    for (const row of rows) {
      const list = byBucket.get(row.bucket_id) ?? []
      list.push(row)
      byBucket.set(row.bucket_id, list)
    }

    for (const [bucket, entries] of byBucket) {
      for (const chunk of chunks(entries, REMOVE_CHUNK)) {
        const names = [...new Set(chunk.map((entry) => entry.object_name))]
        let removed: Set<string> | null = null
        let message = ''
        try {
          const { data, error } = await admin.storage.from(bucket).remove(names)
          if (error) message = error.message
          else removed = new Set((data ?? []).map((object) => object.name))
        } catch (err) {
          message = err instanceof Error ? err.message : String(err)
        }
        if (removed === null) {
          console.error('[purge-attachments] remove failed', bucket, chunk.length, message)
          for (const row of chunk) failed.push({ row, message: message.slice(0, 500) })
          continue
        }
        const counted = new Set<string>()
        for (const row of chunk) {
          if (removed.has(row.object_name) && !counted.has(row.object_name)) {
            counted.add(row.object_name)
            purged += 1
          } else {
            alreadyGone += 1
          }
          done.push(row.id)
        }
      }
    }

    for (const ids of chunks(done, ID_CHUNK)) {
      const { error } = await admin.from('storage_deletion_queue').delete().in('id', ids)
      // The objects are gone; a leftover entry is harmless (alreadyGone on the next run).
      if (error) console.error('[purge-attachments] could not dequeue', ids.length, error.message)
    }

    // One update per distinct attempts value (usually one), chunked by id.
    const now = new Date().toISOString()
    const byAttempts = new Map<string, { attempts: number; message: string; ids: number[] }>()
    for (const { row, message } of failed) {
      const key = `${row.attempts}\u0000${message}`
      const group = byAttempts.get(key) ?? { attempts: row.attempts, message, ids: [] }
      group.ids.push(row.id)
      byAttempts.set(key, group)
    }
    for (const group of byAttempts.values()) {
      for (const ids of chunks(group.ids, ID_CHUNK)) {
        const { error } = await admin
          .from('storage_deletion_queue')
          .update({ attempts: group.attempts + 1, last_error: group.message, last_attempt_at: now })
          .in('id', ids)
        if (error) console.error('[purge-attachments] could not record failure', error.message)
      }
    }

    const [retry, dead] = await Promise.all([
      admin
        .from('storage_deletion_queue')
        .select('id', { count: 'exact', head: true })
        .lt('attempts', MAX_ATTEMPTS),
      admin
        .from('storage_deletion_queue')
        .select('id', { count: 'exact', head: true })
        .gte('attempts', MAX_ATTEMPTS),
    ])
    if (retry.error || dead.error) {
      throw new AppError(500, 'internal', 'Could not count the deletion queue')
    }

    return jsonOk({ purged, alreadyGone, retryable: retry.count ?? 0, dead: dead.count ?? 0 }, cors)
  }),
)
