import { execFile } from 'node:child_process'
import { promisify } from 'node:util'

import { SEED_MODULES, SEED_USERS } from '../../fixtures/ids'
import { DB_CONTAINER, DB_URL } from './env'

/**
 * SQL as `postgres` against the local stack, for reading what the UI cannot show (invitation
 * tokens) and for cleaning up. Uses a host `psql` with the local connection string when one is
 * on PATH (GitHub's ubuntu-latest has it) and otherwise `docker exec` into the database
 * container (local Windows/macOS setups without a Postgres client). `E2E_DB_MODE=psql|docker`
 * forces one.
 */
const exec = promisify(execFile)

type Mode = 'psql' | 'docker'
let modePromise: Promise<Mode> | undefined

async function detectMode(): Promise<Mode> {
  const forced = process.env.E2E_DB_MODE
  if (forced === 'psql' || forced === 'docker') return forced
  try {
    await exec('psql', ['--version'])
    return 'psql'
  } catch {
    return 'docker'
  }
}

/** Run one statement (or several separated by `;`) and return psql's unaligned, tuples-only output. */
export async function sql(query: string): Promise<string> {
  modePromise ??= detectMode()
  const mode = await modePromise
  const psqlArgs = ['-X', '-v', 'ON_ERROR_STOP=1', '-At', '-c', query]
  const [command, args] =
    mode === 'psql'
      ? ['psql', [DB_URL, ...psqlArgs]]
      : [
          'docker',
          ['exec', '-i', DB_CONTAINER, 'psql', '-U', 'postgres', '-d', 'postgres', ...psqlArgs],
        ]
  try {
    const { stdout } = await exec(command, args, { maxBuffer: 16 * 1024 * 1024 })
    return stdout.trim()
  } catch (error) {
    const stderr = (error as { stderr?: string }).stderr ?? ''
    throw new Error(`SQL failed (${mode}): ${stderr.trim() || String(error)}\n  ${query}`, {
      cause: error,
    })
  }
}

/** A SQL string literal. Test data is generated by the suite, but quote it properly anyway. */
export function lit(value: string): string {
  return `'${value.replace(/'/g, "''")}'`
}

export async function count(table: string, where = 'true'): Promise<number> {
  return Number(await sql(`select count(*) from ${table} where ${where}`))
}

/** The pending invitation token for `email` in `workspaceId` (tokens are never sent or returned). */
export async function invitationToken(workspaceId: string, email: string): Promise<string> {
  const token = await sql(
    `select token from public.invitations where workspace_id = ${lit(workspaceId)} ` +
      `and lower(email) = ${lit(email.toLowerCase())} and accepted_at is null order by created_at desc limit 1`,
  )
  if (!token) throw new Error(`no pending invitation for ${email} in ${workspaceId}`)
  return token
}

/**
 * Delete auth users whose email starts with `prefix` (always `e2e-<run id>-...`). This is an
 * account deletion: `on_auth_user_deleted` removes the workspaces they owned alone (modules,
 * records and attachment rows cascade; attachment objects are queued in
 * `storage_deletion_queue`) and the FK cascades remove profiles and memberships.
 */
export async function deleteUsersWithPrefix(prefix: string): Promise<number> {
  if (!/^e2e-[a-z0-9]+-/.test(prefix))
    throw new Error(`refusing to delete users by prefix ${prefix}`)
  const deleted = await sql(
    `with gone as (delete from auth.users where email like ${lit(`${prefix}%`)} returning 1) ` +
      `select count(*) from gone`,
  )
  return Number(deleted)
}

/** Users left behind by earlier, aborted runs (older than `hours`). */
export async function deleteStaleE2eUsers(hours = 3): Promise<number> {
  const deleted = await sql(
    `with gone as (delete from auth.users where email like 'e2e-%@example.com' ` +
      `and created_at < now() - interval '${hours} hours' returning 1) select count(*) from gone`,
  )
  return Number(deleted)
}

export interface SeedState {
  aliceMemberships: string
  bobMemberships: string
  clientsRecords: number
}

/** The facts the suite promises to leave untouched (asserted by the global teardown). */
export async function seedState(): Promise<SeedState> {
  const memberships = (userId: string) =>
    sql(
      `select coalesce(string_agg(w.slug || ':' || m.role, ',' order by w.slug), '') ` +
        `from public.workspace_members m join public.workspaces w on w.id = m.workspace_id ` +
        `where m.user_id = ${lit(userId)}`,
    )
  return {
    aliceMemberships: await memberships(SEED_USERS.alice.id),
    bobMemberships: await memberships(SEED_USERS.bob.id),
    clientsRecords: await count('public.records', `module_id = ${lit(SEED_MODULES.clients.id)}`),
  }
}

